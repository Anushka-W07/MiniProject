"""Regenerate data/samples/*.csv and docs/SOURCES.md from the app's definitions.
Run from the repo root:  python scripts/generate_samples.py"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from astrosense.backend import FIELDS, EQUATIONS, make_baseline, make_sample_log

make_baseline(3000, 99).to_csv("data/samples/sample_healthy_training.csv", index=False)
make_sample_log().to_csv("data/samples/sample_telemetry_log.csv", index=False)

with open("docs/SOURCES.md", "w", encoding="utf-8") as f:
    f.write("# Sensor ranges, equations and sources\n\n*Generated by `scripts/generate_samples.py` from `astrosense/backend.py`.*\n\n")
    f.write("## Equations\n\n```\n" + EQUATIONS + "\n```\n\n## Sensor ranges\n\n")
    f.write("| Sensor | Unit | Nominal range | Source |\n|---|---|---|---|\n")
    for x in FIELDS:
        f.write(f"| {x['label']} | {x['unit']} | {x['min']} to {x['max']} | {x['src']} |\n")
    f.write("\nRows marked **ASSUMPTION** have no source yet: replace them with your hardware datasheets.\n")
print("done")
